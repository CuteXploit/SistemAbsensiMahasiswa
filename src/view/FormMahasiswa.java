    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
// 1. Ambil teks keyword yang diketik di kolom cari
String keyword = txtCari.getText().trim();

// 2. Jika kolom cari kosong, langsung reset tabel nampilin semua data
if (    !keyword.equals("")) {
} else {
    tampilData();
    return;
        }

// 3. Buat model tabel baru untuk menampung hasil pencarian
DefaultTableModel model = new DefaultTableModel();
model.addColumn("No");
model.addColumn("NIM");
model.addColumn("Nama");
model.addColumn("Semester");
model.addColumn("Status");
model.addColumn("Prodi");
model.addColumn("Kelas");
model.addColumn("Email");

// 4. Query SQL dengan operator LIKE untuk mencari data berdasarkan NIM atau Nama
String sql = "SELECT * FROM mahasiswa WHERE nim LIKE ? OR nama LIKE ?";

try {
    int no = 1;
    Connection conn = database.Koneksi.getKoneksi();
    PreparedStatement ps = conn.prepareStatement(sql);
    
    // Set parameter keyword dengan wildcard % (pencarian fleksibel)
    ps.setString(1, "%" + keyword + "%");
    ps.setString(2, "%" + keyword + "%");
    
    ResultSet rs = ps.executeQuery();
    
    // Looping masukkan hasil cari ke tabel
    while(rs.next()) {
        model.addRow(new Object[]{
            no++,
            rs.getString("nim"),
            rs.getString("nama"),
            rs.getInt("semester"),
            rs.getString("status"),
            rs.getString("prodi"),
            rs.getString("kelas"),
            rs.getString("email")
        });
    }
    
    // Set hasil pencarian ke JTable
    tblMahasiswa.setModel(model);
    
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Gagal Mencari Data: " + e.getMessage());
}
    }//GEN-LAST:event_btnCariActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    // 1. Ambil teks/pilihan dari komponen GUI
String nim = txtNim.getText().trim();
String nama = txtNama.getText().trim();
String semester = cmbSemester.getSelectedItem().toString();
String status = cmbStatus.getSelectedItem().toString();
String prodi = cmbProdi.getSelectedItem().toString();
String kelas = cmbKelas.getSelectedItem().toString();
String email = txtEmail.getText().trim();

// 2. Validasi standar agar NIM dan Nama tidak boleh kosong
if (nim.equals("") || nama.equals("")) {
    JOptionPane.showMessageDialog(this, "NIM dan Nama tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
    return;
}

// 3. Siapkan query SQL untuk insert data
String sql = "INSERT INTO mahasiswa (nim, nama, semester, status, prodi, kelas, email) VALUES (?, ?, ?, ?, ?, ?, ?)";

try {
    Connection conn = database.Koneksi.getKoneksi();
    PreparedStatement ps = conn.prepareStatement(sql);
    
    // Pasangkan data sesuai urutan tanda tanya (?) di query
    ps.setString(1, nim);
    ps.setString(2, nama);
    ps.setInt(3, Integer.parseInt(semester));
    ps.setString(4, status);
    ps.setString(5, prodi);
    ps.setString(6, kelas);
    ps.setString(7, email);

    // Eksekusi simpan ke MySQL
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Data Mahasiswa Berhasil Disimpan!");
    
    // 4. Panggil lagi method tampilData() biar tabel langsung nge-refresh otomatis
    tampilData();
    
    // 5. Bersihkan kembali kotak inputan di form
    txtNim.setText("");
    txtNama.setText("");
    txtEmail.setText("");
    cmbSemester.setSelectedIndex(0);
    cmbStatus.setSelectedIndex(0);
    cmbProdi.setSelectedIndex(0);
    cmbKelas.setSelectedIndex(0);
    
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Gagal Menyimpan Data: " + e.getMessage());
}
    }//GEN-LAST:event_btnSimpanActionPerformed

