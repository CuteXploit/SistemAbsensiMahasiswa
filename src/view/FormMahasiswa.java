    private void tampilData() {
    // 1. Siapkan model tabel kosong beserta judul kolomnya
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("No");
    model.addColumn("NIM");
    model.addColumn("Nama");
    model.addColumn("Semester");
    model.addColumn("Status");
    model.addColumn("Prodi");
    model.addColumn("Kelas");
    model.addColumn("Email");
    
    try {
        int no = 1;
        // 2. Query buat ambil semua data dari tabel mahasiswa
        String sql = "SELECT * FROM mahasiswa";
        Connection conn = database.Koneksi.getKoneksi();
        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery(sql);
        
        // 3. Looping untuk memasukkan baris demi baris data dari DB ke model tabel
        while(rs.next()) {
            model.addRow(new Object[]{
                no++,
                rs.getString("nim"),
                rs.getString("nama"),
                rs.getInt("semester"),
                rs.getString("status"),
                rs.getString("prodi"),
                rs.getString("kelas"),
                rs.getString("email")
            });
        }
        // 4. Set model yang udah terisi data tadi ke JTable kamu
        tblMahasiswa.setModel(model);
        
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
    }
}

