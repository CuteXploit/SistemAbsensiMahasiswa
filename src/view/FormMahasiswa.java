    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
    // 1. Ambil data dari komponen GUI
String nim = txtNim.getText().trim();
String nama = txtNama.getText().trim();
String semester = cmbSemester.getSelectedItem().toString();
String status = cmbStatus.getSelectedItem().toString();
String prodi = cmbProdi.getSelectedItem().toString();
String kelas = cmbKelas.getSelectedItem().toString();
String email = txtEmail.getText().trim();

// 2. Validasi inputan tidak boleh kosong
if (nim.equals("") || nama.equals("")) {
    JOptionPane.showMessageDialog(this, "Pilih data pada tabel terlebih dahulu yang ingin diubah!", "Peringatan", JOptionPane.WARNING_MESSAGE);
    return;
}

// 3. Query SQL untuk mengupdate data berdasarkan NIM
String sql = "UPDATE mahasiswa SET nama=?, semester=?, status=?, prodi=?, kelas=?, email=? WHERE nim=?";

try {
    Connection conn = database.Koneksi.getKoneksi();
    PreparedStatement ps = conn.prepareStatement(sql);
    
    // Pasangkan data sesuai urutan tanda tanya (?) di query UPDATE
    ps.setString(1, nama);
    ps.setInt(2, Integer.parseInt(semester));
    ps.setString(3, status);
    ps.setString(4, prodi);
    ps.setString(5, kelas);
    ps.setString(6, email);
    ps.setString(7, nim); // WHERE nim=?

    // Eksekusi update ke MySQL
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Data Mahasiswa Berhasil Diubah!");
    
    // 4. Refresh tabel agar data terbaru langsung muncul
    tampilData();
    
    // 5. Bersihkan kembali form inputan dan buka kunci NIM
    txtNim.setText("");
    txtNama.setText("");
    txtEmail.setText("");
    cmbSemester.setSelectedIndex(0);
    cmbStatus.setSelectedIndex(0);
    cmbProdi.setSelectedIndex(0);
    cmbKelas.setSelectedIndex(0);
    txtNim.setEditable(true); // Biar NIM bisa diketik lagi buat input baru
    
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Gagal Mengubah Data: " + e.getMessage());
}    // TODO add your handling code here:
    }//GEN-LAST:event_btnUbahActionPerformed

