    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
// 1. Ambil data dari komponen GUI Dosen
String nidn = txtNidn.getText().trim();
String nama = txtNama.getText().trim();
String prodi = cmbProdi.getSelectedItem().toString();
String noHp = cmbNoHp.getSelectedItem().toString(); // Sesuaikan dengan tipe komponenmu
String email = txtEmail.getText().trim();

// 2. Validasi standar agar NIDN dan Nama tidak boleh kosong
if (nidn.equals("") || nama.equals("")) {
    JOptionPane.showMessageDialog(this, "NIDN dan Nama tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
    return;
}

// 3. Query SQL untuk insert ke tabel dosen
String sql = "INSERT INTO dosen (nidn, nama, prodi, no_hp, email) VALUES (?, ?, ?, ?, ?)";

try {
    Connection conn = database.Koneksi.getKoneksi();
    PreparedStatement ps = conn.prepareStatement(sql);
    
    // Pasangkan data sesuai urutan kolom di tabel dosen
    ps.setString(1, nidn);
    ps.setString(2, nama);
    ps.setString(3, prodi);
    ps.setString(4, noHp);
    ps.setString(5, email);

    // Eksekusi simpan ke MySQL
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Data Dosen Berhasil Disimpan!");
    
    // 4. Refresh tabel dosen agar data langsung muncul
    tampilData();
    
    // 5. Bersihkan kembali form inputan
    txtNidn.setText("");
    txtNama.setText("");
    txtEmail.setText("");
    cmbProdi.setSelectedIndex(0);
    cmbNoHp.setSelectedIndex(0);
    
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Gagal Menyimpan Data Dosen: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void tblDosenMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDosenMouseClicked
// 1. Ambil baris ke berapa yang diklik oleh user
    int baris = tblDosen.rowAtPoint(evt.getPoint());
    
    // 2. Ambil data dari kolom tabel (ingat urutannya: 1=NIDN, 2=Nama, 3=Prodi, 4=No HP, 5=Email)
    String nidn = tblDosen.getValueAt(baris, 1).toString();
    String nama = tblDosen.getValueAt(baris, 2).toString();
    String prodi = tblDosen.getValueAt(baris, 3).toString();
    String noHp = tblDosen.getValueAt(baris, 4).toString();
    String email = tblDosen.getValueAt(baris, 5).toString();
    
    // 3. Set data tersebut agar muncul kembali ke komponen inputan di atas
    txtNidn.setText(nidn);
    txtNama.setText(nama);
    cmbProdi.setSelectedItem(prodi);
    cmbNoHp.setSelectedItem(noHp);
    txtEmail.setText(email);
    
    // 4. Kunci JTextField NIDN agar tidak bisa diedit (karena NIDN adalah Primary Key)
    txtNidn.setEditable(false);        // TODO add your handling code here:
    }//GEN-LAST:event_tblDosenMouseClicked

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
// 1. Ambil data dari komponen GUI Dosen
String nidn = txtNidn.getText().trim();
String nama = txtNama.getText().trim();
String prodi = cmbProdi.getSelectedItem().toString();
String noHp = cmbNoHp.getSelectedItem().toString();
String email = txtEmail.getText().trim();

// 2. Validasi inputan tidak boleh kosong
if (nidn.equals("") || nama.equals("")) {
    JOptionPane.showMessageDialog(this, "Pilih data pada tabel terlebih dahulu yang ingin diubah!", "Peringatan", JOptionPane.WARNING_MESSAGE);
    return;
}

// 3. Query SQL untuk mengupdate data dosen berdasarkan NIDN
String sql = "UPDATE dosen SET nama=?, prodi=?, no_hp=?, email=? WHERE nidn=?";

try {
    Connection conn = database.Koneksi.getKoneksi();
    PreparedStatement ps = conn.prepareStatement(sql);
    
    // Pasangkan data sesuai urutan tanda tanya (?) di query UPDATE dosen
    ps.setString(1, nama);
    ps.setString(2, prodi);
    ps.setString(3, noHp);
    ps.setString(4, email);
    ps.setString(5, nidn); // WHERE nidn=?

    // Eksekusi update ke MySQL
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Data Dosen Berhasil Diubah!");
    
    // 4. Refresh tabel agar data terbaru langsung muncul
    tampilData();
    
    // 5. Bersihkan kembali form inputan dan buka kunci NIDN
    txtNidn.setText("");
    txtNama.setText("");
    txtEmail.setText("");
    cmbProdi.setSelectedIndex(0);
    cmbNoHp.setSelectedIndex(0);
    txtNidn.setEditable(true); // Biar NIDN bisa diketik lagi buat input baru
    
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Gagal Mengubah Data Dosen: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
// 1. Ambil NIDN dari textfield
String nidn = txtNidn.getText().trim();

// 2. Validasi apakah user sudah memilih data yang mau dihapus
if (nidn.equals("")) {
    JOptionPane.showMessageDialog(this, "Pilih data pada tabel terlebih dahulu yang ingin dihapus!", "Peringatan", JOptionPane.WARNING_MESSAGE);
    return;
}

// 3. Munculkan pop-up konfirmasi yakin/tidak
int konfirmasi = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menghapus data dosen dengan NIDN " + nidn + "?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);

// Jika user memilih YES
if (konfirmasi == JOptionPane.YES_OPTION) {
    // Query SQL untuk menghapus data dosen berdasarkan NIDN
    String sql = "DELETE FROM dosen WHERE nidn=?";
    
    try {
        Connection conn = database.Koneksi.getKoneksi();
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, nidn);
        
        // Eksekusi hapus di MySQL
        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data Dosen Berhasil Dihapus!");
        
        // 4. Refresh tabel dosen
        tampilData();
        
        // 5. Bersihkan kembali form inputan dan buka kunci NIDN
        txtNidn.setText("");
        txtNama.setText("");
        txtEmail.setText("");
        cmbProdi.setSelectedIndex(0);
        cmbNoHp.setSelectedIndex(0);
        txtNidn.setEditable(true);
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal Menghapus Data Dosen: " + e.getMessage());
    }
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

