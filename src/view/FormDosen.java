private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("No");
        model.addColumn("NIDN");
        model.addColumn("Nama");
        model.addColumn("Program Studi");
        model.addColumn("No HP");
        model.addColumn("Email");
        
        try {
            int no = 1;
            String sql = "SELECT * FROM dosen";
            Connection conn = database.Koneksi.getKoneksi();
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            
            while(rs.next()) {
                model.addRow(new Object[]{
                    no++,
                    rs.getString("nidn"),
                    rs.getString("nama"),
                    rs.getString("prodi"),
                    rs.getString("no_hp"),
                    rs.getString("email")
                });
            }
            tblDosen.setModel(model); 
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data dosen: " + e.getMessage());
        }
    }

    private void cariData() {
        String keyword = txtCari.getText().trim();
        
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("No");
        model.addColumn("NIDN");
        model.addColumn("Nama");
        model.addColumn("Program Studi");
        model.addColumn("No HP");
        model.addColumn("Email");
        
        String sql = "SELECT * FROM dosen WHERE nidn LIKE ? OR nama LIKE ?";
        
        try {
            int no = 1;
            Connection conn = database.Koneksi.getKoneksi();
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, "%" + keyword + "%");
            ps.setString(2, "%" + keyword + "%");
            
            ResultSet rs = ps.executeQuery();
            
            while (rs.next()) {
                model.addRow(new Object[]{
                    no++,
                    rs.getString("nidn"),
                    rs.getString("nama"),
                    rs.getString("prodi"),
                    rs.getString("no_hp"),
                    rs.getString("email")
                });
            }
            tblDosen.setModel(model);
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal Mencari Data Dosen: " + e.getMessage());
        }
    }
